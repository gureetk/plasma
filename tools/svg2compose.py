"""Turn the boards' inline SVG icons into PlasmaIcon entries (Compose vectors with a stroke-width parameter).

Usage: svg2compose.py icons.json > PlasmaIcons.kt
icons.json maps an icon name (UpperCamelCase) to an <svg> string copied from a board.
"""
import json, sys, xml.etree.ElementTree as ET, re
sys.path.insert(0, __import__("os").path.dirname(__file__))
from svg2vector import element_path, paint, num, fmt

def entries(name, svg):
    svg = re.sub(r'\s(aria-hidden|class|role)="[^"]*"', "", svg)
    root = ET.fromstring(svg)
    vb = [num(v) for v in root.attrib.get("viewBox", "0 0 24 24").split()]
    base = paint(root, {"fill": "black", "stroke": "none", "stroke-width": "1"})
    paths = []
    def walk(node, inherited):
        for el in node:
            st = paint(el, inherited)
            if el.tag.split('}')[-1] == "g":
                walk(el, st); continue
            d = element_path(el)
            if not d: continue
            filled = st.get("fill", "black") not in ("none", "transparent")
            stroked = st.get("stroke", "none") not in ("none", "transparent")
            paths.append((d, filled, stroked))
    walk(root, base)
    stroke = num(base.get("stroke-width"), 2.0)
    for el in root.iter():
        if "stroke-width" in el.attrib: stroke = num(el.attrib["stroke-width"]); break
    cap = base.get("stroke-linecap"); join = base.get("stroke-linejoin")
    for el in root.iter():
        cap = cap or el.attrib.get("stroke-linecap"); join = join or el.attrib.get("stroke-linejoin")
    cap = cap or "butt"; join = join or "miter"
    body = ",\n        ".join(f'IconPath("{d}", fill = {str(f).lower()}, stroke = {str(s).lower()})' for d, f, s in paths)
    return (f'    {name}(\n        {fmt(vb[2])}f, {fmt(vb[3])}f, defaultStroke = {fmt(stroke)}f, '
            f'roundCaps = {str(cap == "round").lower()}, roundJoins = {str(join == "round").lower()},\n        {body},\n    ),')

icons = json.load(open(sys.argv[1]))
print("""// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/svg2compose.py from the boards' inline SVG icons. Edit icons.json, not this file.
package ca.gureet.plasma.core.design.icon

/** Line icons on a 24-unit grid (Lucide style), from the design boards. Draw them with [PlasmaIcon]. */
enum class PlasmaIcons(
    internal val viewportWidth: Float,
    internal val viewportHeight: Float,
    internal val defaultStroke: Float,
    internal val roundCaps: Boolean,
    internal val roundJoins: Boolean,
    internal vararg val paths: IconPath,
) {""")
for n, s in icons.items(): print(entries(n, s))
print("""    ;
}

internal class IconPath(val data: String, val fill: Boolean, val stroke: Boolean)""")
